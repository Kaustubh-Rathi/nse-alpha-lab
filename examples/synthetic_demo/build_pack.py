#!/usr/bin/env python
"""Build a deterministic SYNTHETIC data pack for the mechanics demo.

This is not market data, not a backtest result, and not evidence of anything.
It exists only so a reader who has not downloaded the real data pack can run the
CLI end-to-end and see the shape of the output.

    python examples/synthetic_demo/build_pack.py
    nse-alpha backtest examples/synthetic_demo/hello_alpha.json \
        --pack examples/synthetic_demo/pack

The generated pack is written to ``examples/synthetic_demo/pack/`` and is
ignored by git. Delete it at any time; the script rebuilds it byte-for-byte.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE / "pack"
SPEC = HERE / "hello_alpha.json"

SYMBOLS = 40
START = "2019-01-01"
END = "2023-12-29"
SEED = 20261120


def build(out: Path) -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    sessions = pd.bdate_range(START, END)
    n_days = len(sessions)

    rows = []
    for i in range(SYMBOLS):
        key = f"SYN{i:03d}"
        # No shared drift and no deliberately trending names: this is a
        # mechanics fixture, not a strategy demonstration.
        market = rng.normal(0.0, 0.008, n_days)
        vol = 0.009 + (i % 7) * 0.0015
        rets = market + rng.normal(0.0, vol, n_days)
        close = 100.0 * np.exp(np.cumsum(rets))
        open_ = close * np.exp(rng.normal(0.0, 0.003, n_days))
        volume = rng.integers(20_000, 900_000, n_days)
        for d, o, c, v in zip(sessions, open_, close, volume):
            rows.append({
                "date": d.date(),
                "key": key,
                "symbol": key,
                "open": round(float(o), 4),
                "close": round(float(c), 4),
                "volume": int(v),
            })

    frame = pd.DataFrame(rows)
    out.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(out / "adjusted_bars.parquet", index=False)
    (out / "README.txt").write_text(
        "SYNTHETIC DATA. Generated by examples/synthetic_demo/build_pack.py.\n"
        "Not market data. Not a research result. Do not cite.\n",
        encoding="utf-8",
    )
    return frame


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help=f"output pack directory (default: {DEFAULT_OUT})")
    args = parser.parse_args()
    frame = build(args.out)
    print(f"wrote {args.out} ({len(frame):,} rows, {SYMBOLS} synthetic symbols)")
    print(f"next: nse-alpha backtest {SPEC.relative_to(HERE.parent.parent)} "
          f"--pack {args.out.relative_to(HERE.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
